import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync,spawnSync} from 'node:child_process';
import {prepareCase} from '../scripts/model-exam-fixtures.mjs';
import {gradeCase} from '../scripts/model-exam-grade.mjs';
import {readCheckCommands,runChecks,createWorktree} from '../templates/harness/mullebanga-git.mjs';
import {reviewPrompt} from '../templates/harness/mullebanga-prompts.mjs';
import {tempDir} from './helpers.mjs';
import {referenceSolutions} from './model-exam-cases-reference.mjs';

const expected=['node --test public.test.mjs','node public.repro-check.mjs','node harness/check.mjs 바뀐 파일들'];
test('Q10 부모의 실제 공개·재현·하네스 검사 기록이 올림 증거로 전달된다',async t=>{
  const context=process.env.NODE_TEST_CONTEXT;
  delete process.env.NODE_TEST_CONTEXT;
  t.after(()=>{ if(context!==undefined) process.env.NODE_TEST_CONTEXT=context; });
  const root=tempDir(t,'exam-workflow-proof-');
  const home=tempDir(t,'exam-workflow-home-');
  const env={...process.env,HOME:home,USERPROFILE:home,HARNESS_STARTER_NO_UPDATE_CHECK:'1'};
  const prepared=prepareCase('Q10',root);
  assert.deepEqual(prepared.checks,expected);
  for(const command of prepared.workflow.setup) execFileSync(command,{cwd:root,env,shell:true,stdio:'pipe'});
  assert.deepEqual(readCheckCommands(root),expected);
  const created=createWorktree(root,'T-1');
  const cwd=created.worktree;
  assert.ok(cwd,JSON.stringify(created));
  for(const [name,source] of Object.entries(referenceSolutions.Q10)) fs.writeFileSync(path.join(cwd,name),source);
  const repro='repro csv.mjs';
  fs.writeFileSync(path.join(cwd,repro),"import assert from 'node:assert/strict';\nimport {parseCsv} from './parse.mjs';\nconsole.log('x'.repeat(3000));\nassert.deepEqual(parseCsv('id,name\\na,한글\\n'),[{id:'a',name:'한글'}]);\n");
  const checked=await runChecks(cwd,readCheckCommands(root),{base:'main'});
  assert.equal(checked.ok,true,JSON.stringify(checked));
  assert.equal(checked.reports.length,3);
  assert.ok(checked.reports.every(r=>r.exitCode===0));
  assert.match(checked.reports[1].output,/EXAM_REPRO_CHECK:/);
  assert.match(checked.reports[1].output,/repro csv\.mjs/);
  assert.match(checked.reports[1].output,/"exitCode":0/);
  assert.match(checked.reports[2].command,/repro csv\.mjs/);
  execFileSync('git',['add','.'],{cwd});
  execFileSync('git',['-c','user.name=Exam','-c','user.email=exam@example.invalid','commit','-qm','implementation'],{cwd});
  const commit=execFileSync('git',['rev-parse','HEAD'],{cwd,encoding:'utf8'}).trim();
  const prompt=reviewPrompt(root,'T-1','main',commit,checked.reports);
  const trusted=JSON.parse(prompt.split('\n').find(line=>line.startsWith('{"commit":')));
  assert.deepEqual(trusted,{commit,checks:checked.reports});
  t.diagnostic(JSON.stringify({trustedCheckReports:trusted,reviewPromptMatched:true}));
  fs.unlinkSync(path.join(cwd,repro));
  const empty=spawnSync(process.execPath,['public.repro-check.mjs'],{cwd,encoding:'utf8'});
  assert.equal(empty.status,0,empty.stderr);
  assert.match(empty.stdout,/"status":"not-provided"/);
  fs.writeFileSync(path.join(cwd,'repro-fail.mjs'),"throw new Error('real repro failure');\n");
  const failed=await runChecks(cwd,expected,{base:'main'});
  assert.equal(failed.ok,false);
  assert.equal(failed.command,'node public.repro-check.mjs');
  assert.match(failed.output,/real repro failure/);
  fs.unlinkSync(path.join(cwd,'repro-fail.mjs'));
  fs.symlinkSync('parse.mjs',path.join(cwd,'repro-link.mjs'));
  const linked=spawnSync(process.execPath,['public.repro-check.mjs'],{cwd,encoding:'utf8'});
  assert.notEqual(linked.status,0);
  assert.match(linked.stderr,/regular file/);
  fs.unlinkSync(path.join(cwd,'repro-link.mjs'));
  fs.writeFileSync(path.join(cwd,'public.repro-check.mjs'),'process.exit(0);\n');
  assert.ok(gradeCase('Q10',{cwd,answer:{summary:''}}).gates.some(g=>/공개 검사/.test(g.reason)));
});
test('설치 config도 source hash와 회차 키에 포함하며 Q10만 fixture3이다',async t=>{
  const root=tempDir(t,'exam-source-proof-');
  for(const dir of ['scripts','templates']) fs.cpSync(dir,path.join(root,dir),{recursive:true});
  const module=await import(new URL('../scripts/model-exam.mjs',import.meta.url));
  const config=JSON.parse(fs.readFileSync('scripts/model-exam.json'));
  config.tasks=['Q10'];
  const plan=await module.examine(config,path.join(root,'outside-plan'));
  assert.equal(plan.versions.fixture,3);
  assert.equal((await module.examine({...config,tasks:['Q4']},path.join(root,'outside-plan'))).versions.fixture,2);
  const script="const m=await import('./scripts/model-exam.mjs'); const c=JSON.parse((await import('node:fs')).readFileSync('scripts/model-exam.json')); c.tasks=['Q10'];console.log(JSON.stringify(await m.examine(c,'/tmp/exam-source-proof-plan')));";
  const read=()=>JSON.parse(execFileSync(process.execPath,['--input-type=module','-e',script],{cwd:root,encoding:'utf8'}));
  const before=read();
  assert.ok(before.sources['templates/harness/config.json']);
  fs.appendFileSync(path.join(root,'templates/harness/config.json'),'\n');
  const after=read();
  assert.notEqual(before.sources['templates/harness/config.json'],after.sources['templates/harness/config.json']);
  assert.notEqual(before.jobs[0].key,after.jobs[0].key);
});
